"""Write Docs/Assets.md and Docs/AssetCredits.md for the island assets (plain Python).

    python Tools/assets/make_asset_docs.py [--kit <dir with kit_manifest.json>]

Reads the licence audit (catalog.py), Build/Assets/prepared.json and imported.json, the imported content's size on disk,
and the authors of the Poly Haven scans (api.polyhaven.com, cached in .cache/polyhaven_authors.json). The review renders
from Tools/assets/review_assets.py (Docs/Images/raw/review) become Docs/Images/Review_<Group>_<n>.jpg with the mesh
names under each frame; without them the kit's own preview sheets are used.
"""
import argparse
import json
import os
import shutil
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import catalog  # noqa: E402

DEFAULT_KIT = os.path.normpath(os.path.join(ROOT, "..", "..", "WorldData", "PirateKit"))
CACHE = os.path.join(ROOT, ".cache", "polyhaven_authors.json")


def authors(ids):
    cache = json.load(open(CACHE)) if os.path.exists(CACHE) else {}
    for pid in ids:
        if pid in cache:
            continue
        try:
            req = urllib.request.Request(f"https://api.polyhaven.com/info/{pid}", headers={"User-Agent": "BiomeAutoMaterials-docs/1.0"})
            info = json.load(urllib.request.urlopen(req, timeout=30))
            cache[pid] = {"name": info.get("name", pid), "authors": sorted(info.get("authors", {}).keys())}
        except Exception as e:  # noqa
            cache[pid] = {"name": pid, "authors": [], "error": str(e)}
    os.makedirs(os.path.dirname(CACHE), exist_ok=True)
    json.dump(cache, open(CACHE, "w"), indent=1)
    return cache


def dir_mb(path):
    total = 0
    for base, _, files in os.walk(path):
        total += sum(os.path.getsize(os.path.join(base, f)) for f in files)
    return total / 1e6


def review_sheets():
    """Unreal renders of the imported meshes (12 to a frame, 4 x 3, far row on top) with their names underneath."""
    raw = os.path.join(ROOT, "Docs", "Images", "raw", "review")
    index_p = os.path.join(raw, "review.json")
    if not os.path.exists(index_p):
        return []
    from PIL import Image, ImageDraw
    index = json.load(open(index_p))
    out = []
    for key in sorted(index):
        src = os.path.join(raw, key + ".png")
        if not os.path.exists(src):
            continue
        im = Image.open(src).convert("RGB")
        im = im.resize((1600, int(im.height * 1600 / im.width)), Image.LANCZOS)
        cells = index[key]
        line_h, cols = 22, 4
        rows = (len(cells) + cols - 1) // cols
        sheet = Image.new("RGB", (im.width, im.height + rows * line_h + 10), (24, 24, 24))
        sheet.paste(im, (0, 0))
        d = ImageDraw.Draw(sheet)
        for i, c in enumerate(cells):
            sz = c["size_m"]
            text = f"{i + 1}. {c['mesh'][3:]}  {max(sz):.1f} m"
            d.text((10 + (i % cols) * (im.width // cols), im.height + 6 + (i // cols) * line_h), text, fill=(235, 235, 235))
        name = key + ".jpg"
        sheet.save(os.path.join(ROOT, "Docs", "Images", name), quality=85, optimize=True)
        out.append(name)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kit", default=DEFAULT_KIT)
    args = ap.parse_args()
    manifest = json.load(open(os.path.join(args.kit, "kit_manifest.json"), encoding="utf8"))
    kept, excluded = catalog.audit(manifest)
    build = os.path.join(ROOT, "Build", "Assets")
    prepared = json.load(open(os.path.join(build, "prepared.json"))) if os.path.exists(os.path.join(build, "prepared.json")) else {}
    imported = json.load(open(os.path.join(build, "imported.json"))) if os.path.exists(os.path.join(build, "imported.json")) else {}
    content = os.path.join(ROOT, "Content", "Assets")

    # ---- credits
    ph = {e["name"]: e["source"].rstrip("/").split("/")[-1] for e in kept if e.get("source")}
    who = authors(sorted(set(ph.values())))
    L = ["# Island asset credits", "",
         "Every island asset is either generated by the Polyester Pirates kit's own scripts (released here under CC0) or a",
         "CC0 scan from [Poly Haven](https://polyhaven.com). No attribution is required, but these artists deserve it.",
         "Ships, weapons, wildlife and outfits from the same kit are not part of this pack.", "",
         "| Asset | Poly Haven source | Author(s) |", "|---|---|---|"]
    for name in sorted(ph):
        pid = ph[name]
        w = who.get(pid, {})
        L.append(f"| `{name}` | [{w.get('name', pid)}](https://polyhaven.com/a/{pid}) | {', '.join(w.get('authors', [])) or 'Poly Haven'} |")
    L += ["", f"Generated by the kit ({len(kept) - len(ph)} assets): "
          + ", ".join(f"`{e['name']}`" for e in sorted(kept, key=lambda e: e["name"]) if not e.get("source")) + "."]
    if excluded:
        L += ["", "## Left out", ""] + [f"- `{e['name']}`: {e['reason']}" for e in excluded]
    open(os.path.join(ROOT, "Docs", "AssetCredits.md"), "w", encoding="utf8").write("\n".join(L) + "\n")

    # ---- contact sheets: our own Unreal renders when there are any, else the kit's previews
    review = review_sheets()
    sheets = "" if review else os.path.normpath(os.path.join(args.kit, "..", "..", "Docs", "PirateKit", "Previews", "Sheets"))
    images = []
    if sheets and os.path.isdir(sheets):
        for f in sorted(os.listdir(sheets)):
            top = f.split("_")[0]
            if f.lower().endswith((".jpg", ".png")) and any(k.lower() in f.lower() for k in ("nature", "tree", "rock", "plant", "building",
                                                                                              "dock", "town", "castle", "prop", "furniture", "tavern")):
                dst = f"Assets_{os.path.splitext(f)[0]}.jpg"
                from PIL import Image
                im = Image.open(os.path.join(sheets, f)).convert("RGB")
                if im.width > 1600:
                    im = im.resize((1600, int(im.height * 1600 / im.width)))
                im.save(os.path.join(ROOT, "Docs", "Images", dst), quality=85)
                images.append(dst)
    images += [r for r in review if not r.startswith("Review_Marine")]

    # ---- contents
    by_cat = {}
    for e in kept:
        by_cat.setdefault(e["cat"].replace("\\", "/"), []).append(e)
    total_tris = sum(e["tris"] for e in kept)
    size_imported = dir_mb(content) if os.path.isdir(content) else 0.0
    L = ["# Island assets", "",
         f"{len(kept)} static meshes for building islands, from the Polyester Pirates kit: trees and plants for every climate,",
         "rocks and cliffs, coastal pieces, colonial and medieval buildings, a castle kit, docks, streets and props.",
         "Real-world scale (1 unit = 1 cm), Nanite on every opaque mesh, PBR materials. They ship as a separate release zip",
         "(`BiomeEnvironmentKit-IslandAssets-...zip`) to stay below GitHub's per-file limit. Download all three and unzip each over "
         "the plugin; the assets appear under `Assets/`.", "",
         f"- Triangles in total: {total_tris / 1e6:.1f} M (Nanite streams them; the full-detail meshes are the source).",
         f"- Size in the plugin: {size_imported:.0f} MB of `.uasset` files." if size_imported else "- Size: built on import.",
         "- Collision: buildings, docks, castle, streets, cliffs and coastal rocks use their own triangles (you can walk",
         "  in doors and up stairs); props, trees and loose rocks have a 26-sided hull; grass, flowers, ferns and debris none.",
         "- Textures are capped at 2048 px for pieces over 8 m, 1024 px for most and 512 px for small props.", ""]
    for img in images:
        L += [f"![{img}](Images/{img})", ""]
    L += ["## Scattering per biome", "",
          "`Tools/assets/catalog.py` lists which assets suit each of the 23 biomes (trees, shrubs, ground cover, rocks,",
          "coast, buildings). `Tools/assets/scatter_biome.py` places a biome's set on the open level's landscape by slope",
          "and height above sea level (set `BAM_BIOME=<Name>` and run it in the editor). For dense grass use the Foliage",
          "tool or a landscape grass type with the same meshes.", "",
          "| Biome | Trees | Shrubs | Ground | Rocks | Coast | Buildings |", "|---|---|---|---|---|---|---|"]
    for b, roles in catalog.BIOME_SETS.items():
        cells = [", ".join(roles.get(r, [])) or "-" for r in ("trees", "shrubs", "ground", "rocks", "coast", "buildings")]
        L.append(f"| {b} | " + " | ".join(cells) + " |")
    L += ["", "## Contents", "", "| Category | Asset | Triangles | Size (cm) | Collision |", "|---|---|---|---|---|"]
    for cat in sorted(by_cat):
        for e in sorted(by_cat[cat], key=lambda e: e["name"]):
            col = imported.get(e["name"], {}).get("collision", "")
            sz = " x ".join(str(int(v)) for v in e.get("size_cm", []))
            L.append(f"| {cat} | `{e['name']}` | {e['tris']:,} | {sz} | {col} |")
    L += ["", "## Rebuilding", "",
          "```bash", "python Tools/assets/prepare_glb.py --kit <path to the kit>   # shrink textures into Build/Assets", "```",
          "Then run `Tools/assets/import_assets.py` in the editor (rerunnable; `BAM_ASSETS_FORCE=1` re-imports)."]
    open(os.path.join(ROOT, "Docs", "Assets.md"), "w", encoding="utf8").write("\n".join(L) + "\n")
    print(f"Assets.md ({len(kept)} assets, {len(images)} images, {size_imported:.0f} MB), AssetCredits.md ({len(ph)} Poly Haven)")


if __name__ == "__main__":
    main()
