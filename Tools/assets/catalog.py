def audit(manifest):
    """Split the kit manifest into (kept, excluded) island assets; excluded entries get a 'reason'."""
    kept, excluded = [], []
    for e in manifest:
        top = e["cat"].replace("\\", "/").split("/")[0]
        if top not in ISLAND_CATEGORIES:
            continue
        src = e.get("source", "") or ""
        if src == "" or src.startswith(CC0_PREFIXES):
            if e["name"].startswith("SK_"):
                excluded.append(dict(e, reason="skeletal mesh (wildlife)"))
            else:
                kept.append(e)
        else:
            excluded.append(dict(e, reason=f"source not verifiably CC0: {src}"))
    return kept, excluded


def sets_for(biome):
    """The island roles of a biome plus its sea's marine roles."""
    out = dict(BIOME_SETS.get(biome, {}))
    out.update(MARINE_SETS.get(MARINE_OF.get(biome, ""), {}))
    return out


def check(kept):
    names = {e["name"][3:] if e["name"].startswith("SM_") else e["name"] for e in kept}
    missing = {}
    for b, roles in BIOME_SETS.items():
        for role, lst in roles.items():
            bad = [n for n in lst if n not in names]
            if bad:
                missing[(b, role)] = bad
    return missing


